using System.Collections.Generic;
using UnityEngine;

/*
    Distraction: a playable piano. The player aims at a key and clicks, through the piano's Interactable (type Screen).
    The model has 52 white keys, from A0 to C8 like a real piano. Notes are generated by code, no audio file needed.
*/

public class Piano : MonoBehaviour
{
    [Header("Keys")]
    [SerializeField] private string keyPrefix = "props_148key";
    [SerializeField] private float pressDepth = 0.005f;
    [SerializeField] private float pressSpeed = 20f;
    [SerializeField] private float pressTime = 0.15f;

    [Header("Sound")]
    [SerializeField] private float noteDuration = 1.5f;
    [SerializeField] private float volume = 0.5f;

    // Semitones from A for the white keys of an octave starting on A: A B C D E F G
    private static readonly int[] WhiteKeySemitones = { 0, 2, 3, 5, 7, 8, 10 };
    private const int SampleRate = 44100;

    private readonly List<Transform> keys = new List<Transform>();
    private Mesh[] keyMeshes;
    private Vector3[] restPositions;
    private float[] releaseTimes;
    // Generated the first time each key is played
    private AudioClip[] notes;
    private AudioSource audioSource;

    void Start()
    {
        foreach (Transform child in transform)
        {
            if (child.name.StartsWith(keyPrefix))
            {
                keys.Add(child);
            }
        }
        // Seen from the front (+Z), the player's left is +X, where the lowest note is
        keys.Sort((a, b) => b.localPosition.x.CompareTo(a.localPosition.x));

        keyMeshes = new Mesh[keys.Count];
        restPositions = new Vector3[keys.Count];
        releaseTimes = new float[keys.Count];
        notes = new AudioClip[keys.Count];
        for (int i = 0; i < keys.Count; i++)
        {
            keyMeshes[i] = keys[i].GetComponent<MeshFilter>().sharedMesh;
            restPositions[i] = keys[i].localPosition;
        }

        audioSource = GetComponent<AudioSource>();
        if (audioSource == null)
        {
            audioSource = gameObject.AddComponent<AudioSource>();
            audioSource.spatialBlend = 1f;
        }
        audioSource.playOnAwake = false;
    }

    // Called by the piano's Interactable (type Screen) through onPressed
    public void PlayAimedKey()
    {
        Transform cam = Camera.main.transform;
        int key = FindAimedKey(new Ray(cam.position, cam.forward));
        if (key >= 0)
        {
            PlayKey(key);
        }
    }

    int FindAimedKey(Ray ray)
    {
        // The piano's single collider covers every key, so the ray is tested against each key's mesh instead
        int closestKey = -1;
        float closestDistance = float.MaxValue;
        for (int i = 0; i < keys.Count; i++)
        {
            Ray localRay = new Ray(keys[i].InverseTransformPoint(ray.origin), keys[i].InverseTransformVector(ray.direction));
            if (keyMeshes[i].bounds.IntersectRay(localRay, out float distance) && distance < closestDistance)
            {
                closestDistance = distance;
                closestKey = i;
            }
        }
        return closestKey;
    }

    void PlayKey(int key)
    {
        if (notes[key] == null)
        {
            notes[key] = CreateNote(KeyFrequency(key));
        }
        audioSource.PlayOneShot(notes[key], volume);
        releaseTimes[key] = Time.time + pressTime;
    }

    float KeyFrequency(int key)
    {
        // The lowest key is A0, MIDI note 21, and A4 (MIDI 69) is 440 Hz
        int midiNote = 21 + 12 * (key / 7) + WhiteKeySemitones[key % 7];
        return 440f * Mathf.Pow(2f, (midiNote - 69) / 12f);
    }

    AudioClip CreateNote(float frequency)
    {
        int sampleCount = Mathf.RoundToInt(SampleRate * noteDuration);
        float[] samples = new float[sampleCount];
        for (int i = 0; i < sampleCount; i++)
        {
            float t = (float)i / SampleRate;
            float phase = 2f * Mathf.PI * frequency * t;

            // A few harmonics, a quick attack and an exponential decay sound close enough to a piano
            float wave = Mathf.Sin(phase) + 0.5f * Mathf.Sin(2f * phase) + 0.25f * Mathf.Sin(3f * phase) + 0.125f * Mathf.Sin(4f * phase);
            float envelope = Mathf.Min(1f, t / 0.005f) * Mathf.Exp(-3f * t);
            // Short fade at the end so the note doesn't click when the clip stops
            envelope *= Mathf.Clamp01((noteDuration - t) / 0.05f);

            samples[i] = wave * envelope / 1.875f;
        }

        AudioClip clip = AudioClip.Create("Piano note " + frequency.ToString("0"), sampleCount, 1, SampleRate, false);
        clip.SetData(samples, 0);
        return clip;
    }

    void Update()
    {
        for (int i = 0; i < keys.Count; i++)
        {
            Vector3 target = restPositions[i];
            if (Time.time < releaseTimes[i])
            {
                target += Vector3.down * pressDepth;
            }
            keys[i].localPosition = Vector3.Lerp(keys[i].localPosition, target, Time.deltaTime * pressSpeed);
        }
    }
}
